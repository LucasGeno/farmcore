# Procrastinate's queue as the catalog sees it: functions (signature and body, comments and
# spacing aside), types (enum labels, composite attributes in order), columns (any order: an
# upgrade appends what a fresh schema declares in place), indexes, constraints and triggers.
_QUEUE_CATALOG = (
    r"""SELECT 'function', p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ') '
              || pg_get_function_result(p.oid) || ' ' || regexp_replace(regexp_replace(
                 p.prosrc, '--[^\n]*', '', 'g'), '\s+', ' ', 'g')
         FROM pg_proc p WHERE p.pronamespace = 'public'::regnamespace
          AND p.proname LIKE 'procrastinate\_%'""",
    r"""SELECT 'enum', t.typname || ' ' || string_agg(e.enumlabel, ',' ORDER BY e.enumsortorder)
         FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid
        WHERE t.typname LIKE 'procrastinate\_%' GROUP BY t.typname""",
    r"""SELECT 'composite', t.typname || ' ' || string_agg(
              a.attname || ' ' || format_type(a.atttypid, a.atttypmod), ',' ORDER BY a.attnum)
         FROM pg_type t JOIN pg_class c ON c.oid = t.typrelid AND c.relkind = 'c'
         JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0
        WHERE t.typname LIKE 'procrastinate\_%' GROUP BY t.typname""",
    r"""SELECT 'column', concat_ws(' ', table_name, column_name, udt_name, is_nullable,
              column_default) FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name LIKE 'procrastinate\_%'""",
    r"""SELECT 'index', indexdef FROM pg_indexes
        WHERE schemaname = 'public' AND tablename LIKE 'procrastinate\_%'""",
    r"""SELECT 'constraint', conrelid::regclass || ' ' || pg_get_constraintdef(oid)
         FROM pg_constraint WHERE conrelid::regclass::text LIKE 'procrastinate\_%'""",
    r"""SELECT 'trigger', pg_get_triggerdef(oid) FROM pg_trigger
        WHERE NOT tgisinternal AND tgrelid::regclass::text LIKE 'procrastinate\_%'""",
)


def _queue_catalog(url: str) -> set[tuple[str, str]]:
    with psycopg.connect(_libpq(url)) as conn:
        return {tuple(row) for q in _QUEUE_CATALOG for row in conn.execute(q)}


def _libpq(url: str) -> str:
    return make_url(url).set(drivername="postgresql").render_as_string(hide_password=False)


def test_head_has_the_installed_task_librarys_queue_schema(settings, scratch_db_url: str) -> None:
    """A lock-file bump that changes Procrastinate's schema needs a revision of its own: the
    chain (core_0009's 3.10 schema, then core_0023's upstream migrations) must build exactly
    what the installed library's own schema.sql builds."""
    from hashlib import sha256
    from importlib.resources import files

    installed = files("procrastinate").joinpath("sql/schema.sql").read_bytes()
    script = ScriptDirectory.from_config(alembic_config()).get_revision("core_0023")
    assert sha256(installed).hexdigest() == script.module.LIBRARY_SCHEMA_SHA256

    command.upgrade(alembic_config(scratch_db_url), "head")
    fresh, drop = _scratch_database(settings)
    try:
        with psycopg.connect(_libpq(fresh), autocommit=True) as conn:
            conn.execute(installed.decode())
        assert _queue_catalog(scratch_db_url) == _queue_catalog(fresh)
    finally:
        drop()


def test_a_3_10_queue_upgrades_and_its_jobs_and_new_ones_run_on_the_3_12_library(
    scratch_db_url: str,
) -> None:
    cfg = alembic_config(scratch_db_url)
    command.upgrade(cfg, "core_0022")  # Procrastinate 3.10.0's queue
    with psycopg.connect(_libpq(scratch_db_url), autocommit=True) as conn:
        conn.execute(
            "SELECT procrastinate_defer_jobs_v1(ARRAY[ROW('farmcore', 'probe', 0, 'farm=1', "
            "'probe:farm=1', '{\"n\": 1}', NULL)]::procrastinate_job_to_defer_v1[])"
        )
    command.upgrade(cfg, "head")

    import procrastinate

    ran: list[int] = []
    app = procrastinate.App(
        connector=procrastinate.PsycopgConnector(conninfo=_libpq(scratch_db_url))
    )

    @app.task(name="probe", queue="farmcore")
    def probe(n: int) -> None:
        ran.append(n)

    async def defer_and_work() -> None:
        async with app.open_async():
            await probe.configure(lock="farm=2", queueing_lock="probe:farm=2").defer_async(n=2)
            await app.run_worker_async(wait=False, install_signal_handlers=False)

    asyncio.run(defer_and_work())
    assert sorted(ran) == [1, 2]
    with psycopg.connect(_libpq(scratch_db_url)) as conn:
        assert conn.execute(
            "SELECT status::text, lock_mode::text FROM procrastinate_jobs ORDER BY id"
        ).fetchall() == [("succeeded", "ordered"), ("succeeded", "ordered")]


def test_core_0023_downgrade_restores_the_3_10_queue_or_refuses_a_mutex_job(
    scratch_db_url: str,
) -> None:
    cfg = alembic_config(scratch_db_url)
    command.upgrade(cfg, "core_0022")
    before = _queue_catalog(scratch_db_url)
    command.upgrade(cfg, "head")
    jobs = (
        "INSERT INTO procrastinate_jobs (queue_name, task_name, lock, lock_mode, args) "
        "VALUES ('farmcore', 'probe', 'farm=1', 'ordered', '{}'), "
        "('farmcore', 'probe', 'farm=2', 'mutex', '{}')"
    )
    with psycopg.connect(_libpq(scratch_db_url), autocommit=True) as conn:
        conn.execute(jobs)

    with pytest.raises(MigrationRefused, match="1 queued job"):
        command.downgrade(cfg, "core_0022")
    with psycopg.connect(_libpq(scratch_db_url), autocommit=True) as conn:
        conn.execute("DELETE FROM procrastinate_jobs WHERE lock_mode = 'mutex'")
    command.downgrade(cfg, "core_0022")

    assert _queue_catalog(scratch_db_url) == before
    with psycopg.connect(_libpq(scratch_db_url)) as conn:
        assert conn.execute("SELECT lock FROM procrastinate_jobs").fetchall() == [("farm=1",)]


