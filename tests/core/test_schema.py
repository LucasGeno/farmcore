IDENTITY_TABLES = {"local_identity", "farm_membership", "local_session", "login_bucket"}


def _tables(session) -> set[str]:
    return set(
        session.execute(
            text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
        ).scalars()
    )


@pytest.fixture
def scratch_db_url(settings) -> Iterator[str]:
    """An empty throwaway database (PostGIS only) for migration round trips."""
    admin_url = make_url(settings.test_database_url)
    name = f"farmcore_test_mig_{uuid.uuid4().hex[:8]}"
    admin = create_engine(admin_url, isolation_level="AUTOCOMMIT")
    with admin.connect() as conn:
        conn.execute(text(f'CREATE DATABASE "{name}"'))
    url = admin_url.set(database=name).render_as_string(hide_password=False)
    try:
        yield url
    finally:
        with admin.connect() as conn:
            conn.execute(text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))
        admin.dispose()


def _public_tables(url: str) -> set[str]:
    eng = create_engine(url)
    try:
        with eng.connect() as conn:
            return _tables(conn)
    finally:
        eng.dispose()


def test_downgrade_to_core_0001_and_upgrade_again(scratch_db_url: str) -> None:
    cfg = alembic_config(scratch_db_url)
    command.upgrade(cfg, "head")
    assert _public_tables(scratch_db_url) >= CANONICAL_TABLES | IDENTITY_TABLES

    command.downgrade(cfg, "core_0001")
    left = _public_tables(scratch_db_url)
    assert not left & (CANONICAL_TABLES | IDENTITY_TABLES)
    assert {"app_module", "clock_state"} <= left

    command.upgrade(cfg, "head")
    assert _public_tables(scratch_db_url) >= CANONICAL_TABLES | IDENTITY_TABLES


