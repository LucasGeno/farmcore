def test_identity_upgrade_keeps_legacy_farms_and_grants_without_inferred_members(
    scratch_db_url: str,
) -> None:
    cfg = alembic_config(scratch_db_url)
    command.upgrade(cfg, "inventory_0001")
    engine = create_engine(scratch_db_url)
    try:
        with engine.begin() as conn:
            farm_id = conn.execute(
                text("INSERT INTO farm (name) VALUES ('Existing family farm') RETURNING id")
            ).scalar_one()
            for grantee in ("owner", "farmer"):
                conn.execute(
                    text(
                        "INSERT INTO data_grant (farm_id, grantee, scopes, purpose, valid_from) "
                        "VALUES (:farm_id, :grantee, ARRAY['*']::text[], 'legacy', now())"
                    ),
                    {"farm_id": farm_id, "grantee": grantee},
                )
        command.upgrade(cfg, "head")
        with engine.connect() as conn:
            assert (
                conn.execute(text("SELECT name FROM farm")).scalar_one() == "Existing family farm"
            )
            assert conn.execute(
                text("SELECT grantee, farm_id FROM data_grant ORDER BY grantee")
            ).all() == [("farmer", farm_id), ("owner", farm_id)]
            for table in IDENTITY_TABLES:
                assert conn.execute(text(f"SELECT count(*) FROM {table}")).scalar_one() == 0
        command.downgrade(cfg, "inventory_0001")
        assert not (_public_tables(scratch_db_url) & IDENTITY_TABLES)
        with engine.connect() as conn:
            assert conn.execute(text("SELECT count(*) FROM farm")).scalar_one() == 1
            assert conn.execute(text("SELECT count(*) FROM data_grant")).scalar_one() == 2
        command.upgrade(cfg, "head")
        assert _public_tables(scratch_db_url) >= IDENTITY_TABLES
    finally:
        engine.dispose()


def test_recipient_binding_preserves_legacy_data_and_round_trips(scratch_db_url: str) -> None:
    cfg = alembic_config(scratch_db_url)
    command.upgrade(cfg, "core_0003")
    engine = create_engine(scratch_db_url)
    grant_rows = text(
        "SELECT id, farm_id, grantee, scopes, purpose, valid_from, valid_to, revoked_at "
        "FROM data_grant ORDER BY id"
    )
    try:
        with engine.begin() as conn:
            farm_id = conn.execute(
                text("INSERT INTO farm (name) VALUES ('Existing grant farm') RETURNING id")
            ).scalar_one()
            identity_id = conn.execute(
                text(
                    "INSERT INTO local_identity (login, password_hash) "
                    "VALUES ('farmer', 'existing-hash') RETURNING id"
                )
            ).scalar_one()
            conn.execute(
                text(
                    "INSERT INTO farm_membership (identity_id, farm_id, role) "
                    "VALUES (:identity_id, :farm_id, 'owner')"
                ),
                {"identity_id": identity_id, "farm_id": farm_id},
            )
            conn.execute(
                text(
                    "INSERT INTO local_session (token_hash, identity_id, csrf_hash, expires_at) "
                    "VALUES (repeat('a', 64), :identity_id, repeat('b', 64), "
                    "now() + interval '12 hours')"
                ),
                {"identity_id": identity_id},
            )
            for grantee in ("owner", "farmer"):
                conn.execute(
                    text(
                        "INSERT INTO data_grant (farm_id, grantee, scopes, purpose, valid_from) "
                        "VALUES (:farm_id, :grantee, ARRAY['fields:read']::text[], 'legacy', :ts)"
                    ),
                    {"farm_id": farm_id, "grantee": grantee, "ts": T0},
                )
            original_grants = conn.execute(grant_rows).all()
            original_session = conn.execute(text("SELECT * FROM local_session")).one()
            original_membership = conn.execute(text("SELECT * FROM farm_membership")).one()

        command.upgrade(cfg, "head")
        with engine.connect() as conn:
            schema = inspect(conn)
            column = next(
                c for c in schema.get_columns("data_grant") if c["name"] == "recipient_identity_id"
            )
            assert column["nullable"] is True
            assert isinstance(column["type"], BigInteger)
            assert conn.execute(grant_rows).all() == original_grants
            assert conn.execute(text("SELECT recipient_identity_id FROM data_grant")).all() == [
                (None,),
                (None,),
            ]
            assert conn.execute(text("SELECT * FROM local_session")).one() == original_session
            assert conn.execute(text("SELECT * FROM farm_membership")).one() == original_membership
            foreign_key = next(
                fk
                for fk in schema.get_foreign_keys("data_grant")
                if fk["constrained_columns"] == ["recipient_identity_id"]
            )
            assert foreign_key["name"] == "fk_data_grant_recipient_identity_id_local_identity"
            assert foreign_key["referred_table"] == "local_identity"
            assert foreign_key["referred_columns"] == ["id"]
            assert (
                conn.execute(
                    text(
                        "SELECT confdeltype FROM pg_constraint "
                        "WHERE conname='fk_data_grant_recipient_identity_id_local_identity'"
                    )
                ).scalar_one()
                == "a"
            )
            index = next(
                i
                for i in schema.get_indexes("data_grant")
                if i["name"] == "ix_data_grant_recipient_identity_id"
            )
            assert index["column_names"] == ["recipient_identity_id"]
            assert index["unique"] is False

        with (
            pytest.raises(
                IntegrityError, match="fk_data_grant_recipient_identity_id_local_identity"
            ),
            engine.begin() as conn,
        ):
            conn.execute(text("UPDATE data_grant SET recipient_identity_id=9223372036854775807"))
        with engine.begin() as conn:
            recipient_id = conn.execute(
                text(
                    "INSERT INTO local_identity (login, password_hash) "
                    "VALUES ('recipient', 'existing-hash') RETURNING id"
                )
            ).scalar_one()
            conn.execute(
                text(
                    "UPDATE data_grant SET recipient_identity_id=:recipient_id "
                    "WHERE grantee='farmer'"
                ),
                {"recipient_id": recipient_id},
            )
        with (
            pytest.raises(
                IntegrityError, match="fk_data_grant_recipient_identity_id_local_identity"
            ),
            engine.begin() as conn,
        ):
            conn.execute(text("DELETE FROM local_identity WHERE id=:id"), {"id": recipient_id})

        command.downgrade(cfg, "core_0003")
        with engine.connect() as conn:
            assert "recipient_identity_id" not in {
                c["name"] for c in inspect(conn).get_columns("data_grant")
            }
            assert conn.execute(grant_rows).all() == original_grants
            assert conn.execute(text("SELECT * FROM local_session")).one() == original_session
            assert conn.execute(text("SELECT * FROM farm_membership")).one() == original_membership
            assert conn.execute(text("SELECT count(*) FROM local_identity")).scalar_one() == 2
        command.upgrade(cfg, "head")
        with engine.connect() as conn:
            assert conn.execute(grant_rows).all() == original_grants
            assert conn.execute(text("SELECT recipient_identity_id FROM data_grant")).all() == [
                (None,),
                (None,),
            ]
    finally:
        engine.dispose()


def _farm(session) -> Farm:
    farm = Farm(name="Test farm")
    session.add(farm)
    session.flush()
    return farm


@settings(
    max_examples=20,
    deadline=None,
    suppress_health_check=[HealthCheck.function_scoped_fixture],
)
@given(recipient_id=st.integers(min_value=-(2**63), max_value=-1))
def test_grant_recipient_fk_rejects_unknown_ids_without_changing_grant(session, recipient_id):
    # Each example creates its own grant; nested rollback preserves the shared fixture session.
    grant = DataGrant(
        farm_id=_farm(session).id,
        grantee="property recipient",
        scopes=["fields:read"],
        purpose="FK property",
        valid_from=T0,
    )
    session.add(grant)
    session.flush()
    grant_id = grant.id
    with (
        pytest.raises(IntegrityError, match="fk_data_grant_recipient_identity_id_local_identity"),
        session.begin_nested(),
    ):
        grant.recipient_identity_id = recipient_id
        session.flush()
    assert session.get(DataGrant, grant_id).recipient_identity_id is None


