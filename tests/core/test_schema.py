def test_multipolygon_from_geojson_reads_back_with_srid_4326(session) -> None:
    farm_id = _farm(session).id
    parcel_id = session.execute(
        text(
            "INSERT INTO parcel (farm_id, name, alias, area_ha, geom) VALUES "
            "(:farm_id, 'Parcel A', 'a', 1.0, ST_SetSRID(ST_GeomFromGeoJSON(:gj), 4326)) "
            "RETURNING id"
        ),
        {"farm_id": farm_id, "gj": MULTIPOLYGON_GEOJSON},
    ).scalar_one()
    srid, kind = session.execute(
        text("SELECT ST_SRID(geom), GeometryType(geom) FROM parcel WHERE id = :id"),
        {"id": parcel_id},
    ).one()
    assert (srid, kind) == (4326, "MULTIPOLYGON")
    column = session.execute(
        text(
            "SELECT srid, type FROM geometry_columns "
            "WHERE f_table_name = 'parcel' AND f_geometry_column = 'geom'"
        )
    ).one()
    assert tuple(column) == (4326, "MULTIPOLYGON")


def test_deleting_a_log_cascades_to_parcel_links_quantities_and_sources(session) -> None:
    farm = _farm(session)
    parcel = Parcel(
        farm_id=farm.id,
        name="Parcel A",
        alias="a",
        area_ha=Decimal("1.0"),
        geom=func.ST_SetSRID(func.ST_GeomFromGeoJSON(MULTIPOLYGON_GEOJSON), 4326),
    )
    product = Product(
        name="Copper",
        authorisation_no="0000000",
        active_substance="copper",
        product_type="contact",
        targets=["downy"],
    )
    session.add_all([parcel, product])
    session.flush()
    log = Log(farm_id=farm.id, type="spray", status="done", name="Spray A", ts_start=T0)
    log.parcels.append(parcel)
    log.quantities.append(
        Quantity(product_id=product.id, measure="rate", value=Decimal("2.5"), unit="kg/ha")
    )
    log.sources.append(LogSource(source_type="voice", external_key="msg-1", precision_rank=1))
    session.add(log)
    session.flush()
    linked = "SELECT count(*) FROM {table} WHERE log_id = :id"
    tables = ("log_parcel", "quantity", "log_source")
    for table in tables:
        assert session.execute(text(linked.format(table=table)), {"id": log.id}).scalar() == 1

    session.execute(text("DELETE FROM log WHERE id = :id"), {"id": log.id})

    for table in tables:
        assert session.execute(text(linked.format(table=table)), {"id": log.id}).scalar() == 0
