def test_multipolygon_from_geojson_reads_back_with_srid_4326(session) -> None:
    farm_id = _farm(session).id
    parcel_id = session.execute(
        text(
            "INSERT INTO parcel (farm_id, name, alias, area_ha, geom) VALUES "
            "(:farm_id, 'Parcel A', 'a', 1.0, ST_SetSRID(ST_GeomFromGeoJSON(:gj), 4326)) "
            "RETURNING id"
        ),
        {"farm_id": farm_id, "gj": MULTIPOLYGON_GEOJSON},
    ).scalar_one()
    srid, kind = session.execute(
        text("SELECT ST_SRID(geom), GeometryType(geom) FROM parcel WHERE id = :id"),
        {"id": parcel_id},
    ).one()
    assert (srid, kind) == (4326, "MULTIPOLYGON")
    column = session.execute(
        text(
            "SELECT srid, type FROM geometry_columns "
            "WHERE f_table_name = 'parcel' AND f_geometry_column = 'geom'"
        )
    ).one()
    assert tuple(column) == (4326, "MULTIPOLYGON")


def test_deleting_a_log_cascades_to_parcel_links_quantities_and_sources(session) -> None:
    farm = _farm(session)
    parcel = Parcel(
        farm_id=farm.id,
        name="Parcel A",
        alias="a",
        area_ha=Decimal("1.0"),
        geom=func.ST_SetSRID(func.ST_GeomFromGeoJSON(MULTIPOLYGON_GEOJSON), 4326),
    )
    session.add(parcel)
    product = add_product(session, "Copper", authorisation_no="0000000", targets=["downy"])
    log = Log(farm_id=farm.id, type="spray", status="done", name="Spray A", ts_start=T0)
    log.parcels.append(parcel)
    log.typed_quantities.append(
        typed_quantity(
            catalog_item_id=product.id, entered_measure="rate", value=Decimal("2.5"), unit="kg/ha"
        )
    )
    log.sources.append(LogSource(source_type="voice", external_key="msg-1", precision_rank=1))
    session.add(log)
    session.flush()
    linked = "SELECT count(*) FROM {table} WHERE log_id = :id"
    tables = ("log_parcel", "typed_quantity", "log_source")
    for table in tables:
        assert session.execute(text(linked.format(table=table)), {"id": log.id}).scalar() == 1

    session.execute(text("DELETE FROM log WHERE id = :id"), {"id": log.id})

    for table in tables:
        assert session.execute(text(linked.format(table=table)), {"id": log.id}).scalar() == 0


def test_catalog_upgrade_reads_legacy_rows_without_inventing_facts(scratch_db_url: str) -> None:
    """A populated core_0005 database upgrades: its products and quantities read through the
    neutral views with what was entered; no authorisation country, crop code or standard value
    is guessed (an unknown unit and a NaN value stay null); downgrade refuses while an entered
    catalog fact exists, then round-trips."""
    cfg = alembic_config(scratch_db_url)
    command.upgrade(cfg, "core_0005")
    engine = create_engine(scratch_db_url)
    try:
        with engine.begin() as conn:
            farm_id = conn.execute(
                text("INSERT INTO farm (name) VALUES ('Legacy') RETURNING id")
            ).scalar_one()
            product_id = conn.execute(
                text(
                    "INSERT INTO product (name, authorisation_no, active_substance, product_type, "
                    "targets) VALUES ('Copper', '9800474', 'copper', 'contact', "
                    "ARRAY['downy']) RETURNING id"
                )
            ).scalar_one()
            log_id = conn.execute(
                text(
                    "INSERT INTO log (farm_id, type, status, name, ts_start, bbch) VALUES "
                    "(:farm, 'spray', 'done', 'legacy spray', :ts, NULL) RETURNING id"
                ),
                {"farm": farm_id, "ts": T0},
            ).scalar_one()
            for value, unit, product in (
                ("800", "g/ha", product_id),
                ("3", "bottles/ha", None),
                ("NaN", "kg/ha", None),
            ):
                conn.execute(
                    text(
                        "INSERT INTO quantity (log_id, product_id, measure, value, unit, label) "
                        "VALUES (:log, :product, 'rate', CAST(:value AS numeric), :unit, 'x')"
                    ),
                    {"log": log_id, "product": product, "value": value, "unit": unit},
                )
        command.upgrade(cfg, "core_0017")  # core_0018 refuses the NaN dose (its own test)
        with engine.begin() as conn:
            assert conn.execute(
                text(
                    "SELECT name, product_type, targets FROM legacy_catalog_item "
                    "WHERE product_id = :p"
                ),
                {"p": product_id},
            ).one() == ("Copper", "contact", ["downy"])
            rows = conn.execute(
                text(
                    "SELECT entered_value::text, entered_unit, measure, value, unit "
                    "FROM legacy_typed_quantity ORDER BY legacy_quantity_id"
                )
            ).all()
            assert rows == [
                ("800", "g/ha", "mass_rate", Decimal("0.800"), "kg/ha"),
                ("3", "bottles/ha", None, None, None),
                ("NaN", "kg/ha", None, None, None),
            ]
            for entered in ("catalog_item", "catalog_authorisation", "typed_quantity"):
                assert conn.execute(text(f"SELECT count(*) FROM {entered}")).scalar() == 0
            assert conn.execute(text("SELECT crop_eppo, bbch FROM log")).one() == (None, None)
            conn.execute(text("UPDATE log SET crop_eppo = 'VITVI'"))
        with pytest.raises(RuntimeError, match="downgrade refused"):
            command.downgrade(cfg, "core_0005")
        with engine.begin() as conn:
            assert conn.execute(text("SELECT crop_eppo FROM log")).scalar_one() == "VITVI"
            conn.execute(text("UPDATE log SET crop_eppo = NULL"))
        command.downgrade(cfg, "core_0005")
        with engine.connect() as conn:
            assert conn.execute(text("SELECT count(*) FROM quantity")).scalar_one() == 3
        command.upgrade(cfg, "core_0017")
    finally:
        engine.dispose()


def test_module_generation_upgrade_keeps_switched_off_apps_off(scratch_db_url: str) -> None:
    """core_0014 on a populated installation: states survive both ways; a state change, however
    made, moves the generation the task fence compares."""
    cfg = alembic_config(scratch_db_url)
    command.upgrade(cfg, "core_0013")
    engine = create_engine(scratch_db_url)
    try:
        with engine.begin() as conn:
            conn.execute(
                text(
                    "INSERT INTO app_module (name, state, version) VALUES "
                    "('kpi', 'uninstalled', '0.1.0'), ('forecast', 'installed', '0.1.0')"
                )
            )
        command.upgrade(cfg, "core_0014")
        with engine.begin() as conn:
            rows = "SELECT name, state, generation, settings FROM app_module ORDER BY name"
            assert conn.execute(text(rows)).all() == [
                ("forecast", "installed", 0, {}),
                ("kpi", "uninstalled", 0, {}),
            ]
            conn.execute(text("UPDATE app_module SET state = 'installed' WHERE name = 'kpi'"))
            conn.execute(text("UPDATE app_module SET version = '0.2.0' WHERE name = 'forecast'"))
            assert conn.execute(text(rows)).all() == [
                ("forecast", "installed", 0, {}),
                ("kpi", "installed", 1, {}),
            ]
        command.downgrade(cfg, "core_0013")
        with engine.begin() as conn:
            assert conn.execute(text("SELECT count(*) FROM app_module")).scalar_one() == 2
    finally:
        engine.dispose()
